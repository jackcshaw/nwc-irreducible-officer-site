// Record the reliance interactive in real time (Playwright video), then encode MP4 and GIF.
import { chromium } from "/Users/jackcshaw-2/dev/comprendo-clients/nwc-irreducible-officer-site/node_modules/playwright/index.mjs";
import { mkdirSync, rmSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
const shots = new URL("../shots/", import.meta.url).pathname;
const vdir = `${shots}.video/`;
rmSync(vdir, { recursive: true, force: true }); mkdirSync(vdir);
const size = { width: 1000, height: 820 };
const b = await chromium.launch();
const c = await b.newContext({ viewport: size, recordVideo: { dir: vdir, size } });
const p = await c.newPage();
await p.goto("http://127.0.0.1:5263/reliance.html");
await p.evaluate(() => document.fonts.ready);
await p.evaluate(() => { document.documentElement.style.scrollBehavior = "smooth"; });
const scrollTo = (sel, offset = 16) => p.evaluate(([s, o]) => scrollTo({ top: document.querySelector(s).getBoundingClientRect().top + scrollY - o, behavior: "smooth" }), [sel, offset]);
await scrollTo("#reliance", 8); await p.waitForTimeout(1600);
await p.check("input[name=call-a][value=rely]"); await p.waitForTimeout(900);
await p.check("input[name=call-b][value=rely]"); await p.waitForTimeout(900);
await scrollTo("[data-field]", 40); await p.waitForTimeout(700);
await p.click("[data-reveal]"); await p.waitForTimeout(1500);
await scrollTo(".task[data-task=b] .result", 260); await p.waitForTimeout(2600);
await scrollTo("[data-stage=quality]", 24); await p.waitForTimeout(1600);
await p.check("input[name=call-q][value=without]"); await p.waitForTimeout(2600);
await scrollTo("[data-stage=account]", 24); await p.waitForTimeout(3200);
await c.close(); await b.close();
const webm = vdir + readdirSync(vdir).find((f) => f.endsWith(".webm"));
const D = "/Users/jackcshaw-2/dev/comprendo-clients/judgment-lab-showreel/node_modules/@remotion/compositor-darwin-arm64";
const ff = (args) => execFileSync(`${D}/ffmpeg`, ["-hide_banner", "-loglevel", "error", "-y", ...args], { env: { ...process.env, DYLD_LIBRARY_PATH: D } });
ff(["-i", webm, "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "22", "-movflags", "+faststart", `${shots}reliance-walkthrough.mp4`]);
ff(["-i", webm, "-vf", "scale=520:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=40:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=5:diff_mode=rectangle", "-r", "8", `${shots}reliance-walkthrough.gif`]);
rmSync(vdir, { recursive: true, force: true });
console.log("wrote reliance-walkthrough.mp4 and .gif");
