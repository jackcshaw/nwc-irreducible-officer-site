import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {assertPosterReceipt, posterInputHashes, pngInfo} from '../scripts/figure-posters.mjs';

const root = mkdtempSync(join(tmpdir(), 'motion-poster-'));
try {
  const outputDir = join(root, 'out'); mkdirSync(outputDir);
  const inputs = ['runtime.js', 'edition.json'];
  writeFileSync(join(root, inputs[0]), 'runtime v1');
  writeFileSync(join(root, inputs[1]), '{"cast":"workplace"}');
  // Use a real PNG generated by the existing build; the receipt tests concern
  // input/output identity, while the browser gate checks the actual figure art.
  const png = readFileSync('dist/assets/share-card.png');
  const outputs = Object.fromEntries(['poster.png', 'final.png', 'og.png'].map(file => {
    writeFileSync(join(outputDir, file), png); return [file, pngInfo(png)];
  }));
  const receipt = {schema: 1, variant: 'workplace', inputs: posterInputHashes(root, inputs), outputs};
  const options = {root, outputDir, inputs, variant: 'workplace'};
  assertPosterReceipt(receipt, options);
  assert.throws(() => assertPosterReceipt(receipt, {...options, variant: 'pme'}), /variant/);
  writeFileSync(join(root, 'drawing.js'), 'new dependency');
  assert.throws(() => assertPosterReceipt(receipt, {...options, inputs: [...inputs, 'drawing.js']}), /Stale poster inputs/);
  writeFileSync(join(root, inputs[0]), 'runtime v2');
  assert.throws(() => assertPosterReceipt(receipt, options), /Stale poster inputs/);
  writeFileSync(join(root, inputs[0]), 'runtime v1');
  const changed = Buffer.from(png); changed[changed.length - 1] ^= 1;
  writeFileSync(join(outputDir, 'poster.png'), changed);
  assert.throws(() => assertPosterReceipt(receipt, options), /Stale poster output/);
  assert.throws(() => pngInfo(Buffer.from('not an image')), /not a PNG/);
  console.log('figure poster receipts passed: changed inputs, added dependencies, variant and output identity');
} finally { rmSync(root, {recursive: true, force: true}); }
